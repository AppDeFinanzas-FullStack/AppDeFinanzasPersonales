describe('RecurringService.skip', () => {
  it('TASK-228 omitir pasa la ocurrencia a skipped, sin movimiento, y resuelve el aviso', async () => {
    const userId = await newUser();
    const pending = await pendingOccurrence(userId);

    await recurring.skip(ctxFor(userId), pending.occurrenceId);

    expect(await occurrenceStatus(pending.occurrenceId)).toBe('skipped');
    expect(await transactionsOf(userId)).toEqual([]);
    expect(await noticeStatus(userId, pending.occurrenceId)).toBe('resolved');
  });

  it('RNF-11 omitir una ocurrencia ya decidida da ALREADY_DECIDED', async () => {
    const userId = await newUser();
    const pending = await pendingOccurrence(userId);
    await recurring.skip(ctxFor(userId), pending.occurrenceId);

    const error = await rejectionOf(recurring.skip(ctxFor(userId), pending.occurrenceId));

    expect(error.code).toBe('ALREADY_DECIDED');
    expect(await occurrenceStatus(pending.occurrenceId)).toBe('skipped');
  });

  it('RNF-11 confirmar una ocurrencia omitida da ALREADY_DECIDED y no registra movimiento', async () => {
    const userId = await newUser();
    const pending = await pendingOccurrence(userId);
    await recurring.skip(ctxFor(userId), pending.occurrenceId);

    const error = await rejectionOf(
      recurring.confirm(ctxFor(userId), pending.occurrenceId, confirmInput()),
    );

    expect(error.code).toBe('ALREADY_DECIDED');
    expect(await transactionsOf(userId)).toEqual([]);
    expect(await occurrenceStatus(pending.occurrenceId)).toBe('skipped');
  });

  it('RNF-11 confirmar y omitir a la vez deja una sola decisión', async () => {
    const userId = await newUser();
    const pending = await pendingOccurrence(userId);

    const results = await Promise.allSettled([
      recurring.confirm(ctxFor(userId), pending.occurrenceId, confirmInput()),
      recurring.skip(ctxFor(userId), pending.occurrenceId),
    ]);

    expect(results.filter((result) => result.status === 'fulfilled')).toHaveLength(1);
    const status = await occurrenceStatus(pending.occurrenceId);
    expect(['registered', 'skipped']).toContain(status);
    expect(await transactionsOf(userId)).toHaveLength(status === 'registered' ? 1 : 0);
  });

  it('TASK-228 no omite la ocurrencia de otro usuario', async () => {
    const ownerId = await newUser();
    const otherId = await newUser();
    const pending = await pendingOccurrence(ownerId);

    await rejectionOf(recurring.skip(ctxFor(otherId), pending.occurrenceId));

    expect(await occurrenceStatus(pending.occurrenceId)).toBe('pending');
    expect(await noticeStatus(ownerId, pending.occurrenceId)).toBe('waiting');
  });
});
