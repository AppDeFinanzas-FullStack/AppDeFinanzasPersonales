/**
 * The task fixes `confirm` and `skip` of `RecurringService` (plan §4.14.2) and
 * `ConfirmOccurrenceInput` of `@finanzas/contracts`, but not their signatures. These tests assume:
 * - `createRecurringService(deps)` takes, as in TASK-227, `uow`, `generator`, `rates`,
 *   `ledgerHooks` and `clock` from the container built with `RELEASE=1.2`.
 * - `confirm(ctx, occurrenceId, input)` mirrors `POST /api/recurring/occurrences/:id/confirm`: the
 *   occurrence is the `:id` of the route and `input` its body. `input.transactionId` is the id,
 *   generated by the client (ADR-11), of the transaction it creates. Without `amount` or `date`, the
 *   transaction takes the rule's amount and the occurrence's original date.
 * - `skip(ctx, occurrenceId)` mirrors `POST /api/recurring/occurrences/:id/skip`.
 * - Errors are `AppError`s: `ALREADY_DECIDED`, `ACCOUNT_ARCHIVED`, `CATEGORY_ARCHIVED` and
 *   `FUTURE_DATE`. The plan does not name the error of a rule without amount confirmed without
 *   `amount`, nor of an occurrence of another user, so only the rejection is checked.
 * - "Today" is the local date of `ctx.now` in `ctx.timezone`.
 * - In a transfer from BOB to USD the declared rate is BOB per USD (plan §4.6.1), so 1050.00 BOB at
 *   10.50 arrive as 100.00 USD.
 *
 * The pending occurrences and their `recurring_pending` notices come from the `RecurringGenerator`
 * of TASK-226, over rules written by SQL. Results are read straight by SQL. `market_rate` is global
 * (ADR-12): the rows this file writes are on its own dates, and whatever was there is put back.
 */
interface RecurringServiceUnderTest {
  confirm(ctx: RatesContext, occurrenceId: string, input: ConfirmOccurrenceInput): Promise<unknown>;
  skip(ctx: RatesContext, occurrenceId: string): Promise<unknown>;
}
type CreateRecurringService = (deps: {
  uow: UnitOfWork;
  generator: RecurringGenerator;
  rates: Container['ratesService'];
  ledgerHooks: Container['ledgerHooks'];
  clock: Container['clock'];
}) => RecurringServiceUnderTest;

const { createRecurringService } =
  (await import('../../src/application/services/recurring.service.js')) as unknown as {
    createRecurringService: CreateRecurringService;
  };

